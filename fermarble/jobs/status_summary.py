#!/usr/bin/env python3
"""Short markdown summary of the post-Pi3X evaluation (eval_after_pi3.sh) -> runs/status_lunch.md.

Reads only evaluator outputs (results.json), oracle reports, prediction manifests and run
summaries; every section degrades to a note when its input is missing.
"""
import csv
import json
import math
from pathlib import Path

import numpy as np

R = Path('runs')
OUT = R / 'status_lunch.md'
E = R / 'pi3x-eval'


def res(d):
    p = Path(d) / 'results.json'
    return {r['key']: r for r in json.loads(p.read_text())} if p.is_file() else None


def manifest(d):
    p = Path(d) / 'prediction_manifest.json'
    return json.loads(p.read_text())['clips'] if p.is_file() else None


def table(runs, base):
    """Markdown table: val / val wide / train / all dev, mean/median, better/worse vs `base`, worst loss."""
    B = res(base)
    m = manifest(base)
    groups = [('val', lambda k: m[k]['split'] == 'val'),
              ('val wide', lambda k: m[k]['split'] == 'val' and m[k]['camera_mode'] == 'wide'),
              ('train', lambda k: m[k]['split'] == 'train'), ('all dev', lambda k: True),
              ('flir-VIS', lambda k: m[k]['camera_mode'] == 'flir-VIS')]
    L = ['| run | ' + ' | '.join(g for g, _ in groups) + ' |', '|---' * (len(groups) + 1) + '|']
    for name, d in runs:
        X = res(d)
        if X is None:
            L.append(f'| {name} | ' + ' | '.join('missing' for _ in groups) + ' |')
            continue
        cells = []
        for _, f in groups:
            ks = [k for k in B if f(k)]
            v = np.array([X[k]['drift_pct'] for k in ks])
            dd = v - np.array([B[k]['drift_pct'] for k in ks])
            cells.append(f'{v.mean():.2f} / {np.median(v):.2f} ({(dd < -0.05).sum()}+ {(dd > 0.05).sum()}- worst {dd.max():+.1f})')
        L.append(f'| {name} | ' + ' | '.join(cells) + ' |')
    return L


def main():
    L = ['# Status after lunch run', '',
         'Generated by `fermarble/jobs/status_summary.py` from `fermarble/jobs/eval_after_pi3.sh` '
         '(log `runs/eval_after_pi3.log`). Nothing was uploaded.', '']
    # Pi3X run health
    for name, d in (('dev', R / 'pi3x-dev'), ('test', R / 'pi3x-test')):
        s = d / 'pi3x_summary.json'
        if s.is_file():
            j = json.loads(s.read_text())
            err = [k for k, v in j.items() if 'error' in v]
            L.append(f"- Pi3X {name}: {len(j) - len(err)} clips OK, {len(err)} errors {err if err else ''}")
        else:
            L.append(f'- Pi3X {name}: no summary (run incomplete)')
    L.append('')

    # 1. heading sources per camera type
    L += ['## 1. Heading-only drift: DPVO median vs VGGT vs Pi3X (80 dev clips VGGT covers)', '']
    t = E / 'compare' / 'compare_runs.txt'
    L += (['```'] + t.read_text().split('\n\n')[0].strip().split('\n') + ['```'] if t.is_file()
          else ['(missing: compare-runs failed or did not run)'])
    L.append('')

    # 2. switch source / tie-breaker
    L += ['## 2. Switch at 54.25 deg (+ broken-seed rule), official evaluator, dev',
          'Cells: mean / median (clips better+ worse- vs none, worst single loss).', '']
    L += table([('none (no switch)', R / 'heading-med3-flow-wv'), ('VGGT switch (current default)', R / 'broken-seed/dev'),
                ('Pi3X switch', E / 'dev-pi3x-switch'), ('VGGT switch, Pi3X tie-breaker', E / 'dev-vggt-tiebreak')],
               R / 'heading-med3-flow-wv')
    L.append('')
    for name, d, key in (('Pi3X switch', E / 'dev-pi3x-switch', 'vggt_switch'),
                         ('VGGT switch', R / 'broken-seed/dev', 'vggt_switch'),
                         ('tie-breaker', E / 'dev-vggt-tiebreak', 'vggt_switch')):
        m = manifest(d)
        if m:
            L.append(f"- {name} fires on dev: {', '.join(k[5:] for k, v in m.items() if v.get(key)) or 'none'}")
    m = manifest(E / 'dev-vggt-tiebreak')
    if m:
        vetoed = [k[5:] for k, v in m.items() if 'tiebreak_dpvo_deg' in v and not v.get('vggt_switch')]
        L.append(f"- tie-breaker vetoed (kept DPVO) on dev: {', '.join(vetoed) or 'none'}")
    for name, d in (('Pi3X switch', E / 'test-pi3x-switch'), ('VGGT switch + Pi3X tie-breaker', E / 'test-vggt-tiebreak')):
        m = manifest(d)
        if m:
            L.append(f"- test, {name}: uses foundation-model heading on "
                     f"{', '.join(k[5:] for k, v in m.items() if '+vggt_heading' in v['method']) or 'none'}")
    ch = E / 'test_changes.txt'
    if ch.is_file():
        L += ['', 'Test predictions changed vs the uploaded `submission_test_flow_vggtswitch.json` predictions:', '```',
              ch.read_text().strip(), '```']
    L.append('')

    # 3. Pi3X focal vs focal-sweep labels
    L += ['## 3. Focal estimate vs focal-sweep labels (flir-VIS dev)',
          'label = best focal of the seed-0 sweep (heading only); x2 better = 3-seed median at x2.0 beats x1.0. '
          'Estimate predicts zoom when focal_scale > 1.41 (geometric midpoint of 1 and 2).', '']
    ps, vs, fr = R / 'pi3x-dev/pi3x_summary.json', R / 'vggt-dev/vggt_summary.json', R / 'focal-report/focal_report.csv'
    if ps.is_file() and fr.is_file():
        P, V = json.loads(ps.read_text()), json.loads(vs.read_text())
        L += ['| clip | sweep best | x2 better | Pi3X HFOV | Pi3X scale | VGGT scale | Pi3X right | VGGT right |',
              '|---|---|---|---|---|---|---|---|']
        npr = nvr = n = 0
        for r in csv.DictReader(fr.open()):
            k = r['key']
            if k not in P or 'error' in P[k]:
                continue
            best = min(('1.0', '1.5', '2.0', '2.5'), key=lambda f: float(r[f'diag{f}_head_true_speed']))
            x2 = float(r['f2_med3_true_speed']) < float(r['f1_med3_true_speed'])
            p, v = P[k]['focal_scale'], V[k]['focal_scale']
            pr, vr = (p > math.sqrt(2)) == x2, (v > math.sqrt(2)) == x2
            npr += pr
            nvr += vr
            n += 1
            L.append(f"| {k} | x{best} | {'yes' if x2 else 'no'} | {P[k]['pi3x_hfov_median']:.1f} | {p:.2f} | {v:.2f} | "
                     f"{'yes' if pr else 'no'} | {'yes' if vr else 'no'} |")
        L.append(f'\nPi3X right on {npr}/{n}, VGGT right on {nvr}/{n}.')
    else:
        L.append('(missing Pi3X dev summary or focal report)')
    t = E / 'clip075.txt'
    if t.is_file():
        L += ['', 'clip_075 turn ratio (1.0 = correct) and heading-only drift:', '```', t.read_text().strip(), '```']
    L.append('')

    # 4. oracle focal lower bound
    L += ['## 4. Oracle focal lower bound (reads GT, diagnostic only)', '']
    t = R / 'focal-lb/report/focal_lower_bound.txt'
    L += (['```'] + t.read_text().strip().split('\n') + ['```'] if t.is_file() else ['(missing)'])
    L.append('')
    OUT.write_text('\n'.join(L) + '\n')
    print('written', OUT)


if __name__ == '__main__':
    main()
