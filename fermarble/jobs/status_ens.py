#!/usr/bin/env python3
"""runs/status_ens.md: overnight Pi3X ensembles / windows / VGGT weights on top of kwide_crop (ens_gpu.sh,
ens_eval.sh). Progress of the Pi3X runs, the comparison table, bundles and a one-line recommendation for the
last slot (a variant only if it beats kwide_crop on both train and val). Reads only run outputs."""
import hashlib
import json
from pathlib import Path

R = Path('runs')
O = R / 'ens-eval'
RUNS = ['kf1.5c', 'kf3c', 'kf1', 'kf4', 'w16', 'w32']
KWIDE = R / 'submission_test_pi3x_ir_kwide_crop.json'


def read(p, missing='(not available yet)'):
    p = Path(p)
    return p.read_text().strip() if p.is_file() else missing


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    dev = json.loads((R / 'vggt-dev/vggt_summary.json').read_text())
    split = {k: v['split'] for k, v in dev.items() if 'error' not in v}
    L = ['# Status: overnight Pi3X ensembles for the last slot (on top of kwide_crop, 11.85 on test)', '',
         'Generated by `fermarble/jobs/status_ens.py`. Nothing was uploaded. Base: `runs/submission_test_pi3x_ir_kwide_crop.json` '
         f'(sha256 {sha(KWIDE)[:12]}…). Pi3X frames: crops.json bottom crop, no inpainting.', '']
    c = json.loads((O / 'compare.json').read_text()) if (O / 'compare.json').is_file() else {}
    best = read(O / 'best.txt', '')
    gpu_done = 'GPU DONE' in read(R / 'ens_gpu.log', '')
    if best:
        b, v = c[best]['means'], c['kwide_crop']['means']
        rec = (f"Upload `runs/submission_test_pi3x_ir_kwide_crop_ens_{best}.json` ({best}: val {b['val']:.2f} vs {v['val']:.2f}, "
               f"train {b['train']:.2f} vs {v['train']:.2f}; changes {len(c[best]['test_changed'])} test clips).")
    else:
        rec = ('Re-upload kwide_crop (`runs/submission_test_pi3x_ir_kwide_crop.json`, 11.85): no variant beats it on both '
               'train and val' + ('.' if gpu_done else ' so far (Pi3X runs still going; provisional).'))
    L += [f'**Recommendation for the last slot:** {rec}', '', '## Pi3X runs (clips done / total)', '',
          '| run | test | dev val | dev train |', '|---|---|---|---|']
    for n in RUNS:
        done = {p.stem for d in [R / f'pi3x-dev-{n}/poses'] if d.is_dir() for p in d.glob('*.npz')}
        nt = len(list((R / f'pi3x-test-{n}/poses').glob('*.npz'))) if (R / f'pi3x-test-{n}/poses').is_dir() else 0
        nv = sum(split.get(k) == 'val' for k in done)
        L.append(f"| {n} | {nt}/20 | {nv}/{sum(s == 'val' for s in split.values())} | "
                 f"{sum(split.get(k) == 'train' for k in done)}/{sum(s == 'train' for s in split.values())} |")
    L += ['', '```'] + [x for x in read(R / 'ens_gpu.log', '').splitlines() if x[:2] == '20'] + \
         [x for x in read(R / 'ens_eval.log', '').splitlines() if x[:2] == '20'] + ['```', '',
         '## Variants vs kwide_crop', '',
         'kf1 / kf4 / kf1.5c / kf3c: one Pi3X run at that keyframe rate; mean5 / med5: circular mean / median of 1, 1.5, 2, 3, 4 fps; '
         'mean3 / med3: of 1.5, 2, 3 fps; w16 / w32: 2 fps with window 16 / 32, alone and circular mean with the current run '
         '(w16mean / w32mean); vw0.9 / 0.8 / 0.7: weighted circular mean Pi3X / VGGT; best4: '
         + read(O / 'best4.txt', '(not run yet)') + ' (picked on train).', '', read(O / 'compare.md'), '', '## Bundles (validated, not uploaded)', '']
    bundles = sorted(R.glob('submission_test_pi3x_ir_kwide_crop_ens_*.json'))
    L += [f'- `{b}` (sha256 {sha(b)})' for b in bundles] or ['- none yet']
    (R / 'status_ens.md').write_text('\n'.join(L) + '\n')
    print('written', R / 'status_ens.md')


if __name__ == '__main__':
    main()
