#!/usr/bin/env python3
"""runs/status_last.md: A (Pi3X keyframe settings) and B (rotation-only BA) on top of
kwide_crop_inpaint_auto, refreshed by either job as results come in. Reads only run outputs."""
from pathlib import Path

R = Path('runs')


def read(p, missing='(not finished yet)'):
    p = Path(p)
    return p.read_text().strip() if p.is_file() else missing


def log_lines(p):
    p = Path(p)
    return [x for x in p.read_text().splitlines() if x[:2] == '20'] if p.is_file() else []


def bundles(prefix):
    out = [f"- `{b}` ({b.stat().st_size:,} bytes)" for b in sorted(R.glob(f'submission_test_pi3x_ir_kwide_crop_inpaint_auto_{prefix}*.json'))]
    return out or ['- none built (no variant beats kwide_crop_inpaint_auto on both train and val, or not finished)']


def main():
    L = ['# Status: last-slot experiments (on top of kwide_crop_inpaint_auto)', '',
         'Generated by `fermarble/jobs/status_last.py`. Nothing was uploaded. Base: '
         '`runs/submission_test_pi3x_ir_kwide_crop_inpaint_auto.json` (dev val 11.35, train 12.16).', '',
         '## A. Pi3X keyframe settings (3 fps / 1.5 fps, window 24) and their circular mean with the current 2 fps run', '',
         '```'] + log_lines(R / 'pi3_windows.log') + ['```', '', read(R / 'pi3-windows/compare.md'), '', 'Bundles:'] + bundles('kf') + bundles('mean3')
    L += ['', '## B. Rotation-only BA (static shore features + Pi3X priors), exploratory', '',
          '```'] + log_lines(R / 'rot_ba.log') + ['```', '', read(R / 'rot-ba/summary.md'), '', read(R / 'rot-ba/compare.md'),
                                                  '', 'Bundles:'] + bundles('rotba')
    for src in ('pi3x-clip', 'pi3x-window'):
        L += ['', f'## B with Pi3X intrinsics ({src})', '', read(R / f'rot-ba-{src}/summary.md'), '',
              read(R / f'rot-ba-{src}/compare.md'), '', 'Bundles:'] + bundles(f'rotba_{src}')
    L += ['', '```'] + log_lines(R / 'rot_ba_k.log') + ['```']
    (R / 'status_last.md').write_text('\n'.join(L) + '\n')
    print('written', R / 'status_last.md')


if __name__ == '__main__':
    main()
