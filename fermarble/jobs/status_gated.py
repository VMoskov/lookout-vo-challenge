#!/usr/bin/env python3
"""runs/status_gated.md for gated_pipeline.sh: fitted gate, dev table (official evaluator) vs kwide
and kwide_crop, which dev/test clips use the new flow and the segmentation horizon, the test speed
diagnostics, and the two bundles. Reads only run outputs."""
import json
import os
from pathlib import Path

R = Path('runs')
G = Path(os.environ.get('G', 'runs/gated'))
SUFFIX = os.environ.get('SUFFIX', 'gseg')
STATUS = Path(os.environ.get('STATUS', 'runs/status_gated.md'))


def read(p):
    return Path(p).read_text().strip() if Path(p).is_file() else f'(missing: {p})'


def decisions(split):
    p = G / f'flow-{split}' / 'decisions.json'
    if not p.is_file():
        return ['(missing)']
    d = json.loads(p.read_text())
    new = [k[5:] for k, v in d.items() if v['speed_source'] != 'old']
    segh = [k[5:] for k, v in d.items() if v['horizon'] == 'seg']
    L = [f"- new flow on {len(new)}/{len(d)} clips: {', '.join(new) or 'none'}",
         f"- segmentation horizon chosen on {len(segh)}/{len(d)} clips: {', '.join(segh) or 'none'}"
         + (' (used only where the new flow also passes the flow gate)' if segh else '')]
    if split == 'test':
        L += ['', '| clip | camera | horizon | DPVO-seg row diff (px) / tilt (deg) | old speed | new flow | reliable old -> new | '
              'corr raw | gap (s) | speed used |', '|---|---|---|---|---|---|---|---|---|---|']
        f = lambda x, n=2: '-' if x is None else f'{x:.{n}f}'
        for k, v in d.items():
            L.append(f"| {k[5:]} | {v['camera_mode']} | {v['horizon']} | {f(v['row_diff_px'], 0)} / {f(v['tilt_diff_deg'], 1)} | "
                     f"{'flow' if v['old_fallback'] == 'none' else 'const'} | {v['new_fallback'] or '-'} | "
                     f"{f(v['rel_old'])} -> {f(v['rel_new'])} | {f(v['corr_raw'])} | {f(v['gap_s'], 0)} | "
                     f"**{'new' if v['speed_source'] != 'old' else 'old'}** |")
    return L


def main():
    gate = read(G / 'tune' / 'gate.json')
    L = ['# Status: gated segmentation flow', '',
         'Generated by `fermarble/jobs/status_gated.py` (job `fermarble/jobs/gated_pipeline.sh`, log `runs/gated_pipeline.log`). '
         'Nothing was uploaded.', '',
         'Masked flow (PanSR water only, fixed geometric near/far bands, droplet filter) with three horizons: DPVO (m), '
         'segmentation top edge of water (sa), segmentation water/sky boundary only (sb). Gate (gated_flow.py), all '
         'parameters fitted on TRAIN with the kwide heading (oracle.py --gate-tune):',
         '- horizon: segmentation horizon `hv` only if it differs from DPVO by > T px (centre row) or > D deg (tilt), per clip',
         '- pixels: a band needs >= N water pixels (one-band pairs with stricter reliability)',
         '- flow: new flow only if reliable pairs drop <= X, correlation with the old raw flow >= Y, longest gap < Z s', '',
         '## Fitted gate', '', '```', gate, '```', '', '```', '\n'.join(read(G / 'tune.log').split('\n')[:3]) if (G / 'tune.log').is_file() else '', '```',
         '', '## Dev (official evaluator)', '', read(G / 'compare.md'), '', read(G / 'compare-crop.md'), '',
         '## Dev clips', ''] + decisions('dev') + ['', '## Test clips', ''] + decisions('test')
    L += ['', '## Test speed diagnostics (clips using the new flow)', '', read(G / 'test_speed_diag.md'),
          '', f'Plot: `{G}/test_speed_diag.png`.', '', '## Bundles', '']
    for b in (f'submission_test_pi3x_ir_kwide_{SUFFIX}.json', f'submission_test_pi3x_ir_kwide_crop_{SUFFIX}.json'):
        p = R / b
        L.append(f"- `runs/{b}`: {'built, ' + format(p.stat().st_size, ',') + ' bytes' if p.is_file() else 'NOT built'}")
    L.append('\n' + read(G / 'pack.log'))
    STATUS.write_text('\n'.join(L) + '\n')
    print('written', STATUS)


if __name__ == '__main__':
    main()
