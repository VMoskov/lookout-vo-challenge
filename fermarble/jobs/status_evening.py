#!/usr/bin/env python3
"""runs/status_evening.md: bundles built today, the Pi3X speed job and the Pi3X phase-ensemble job.
Each section notes when its job has not finished yet; both jobs call this at their end."""
import json
from pathlib import Path

R = Path('runs')


def bundle(name):
    p = R / name
    return f'`runs/{name}` ({p.stat().st_size:,} bytes)' if p.is_file() else f'`runs/{name}` (not built)'


def section(title, md, log):
    L = [f'## {title}', '']
    L += [md.read_text().strip()] if md.is_file() else ['(not finished yet)']
    if log.is_file():
        L += ['', 'Job log:', '```'] + [x for x in log.read_text().splitlines() if x[:2] == '20'] + ['```']
    return L + ['']


def main():
    L = ['# Status evening', '', 'Generated by `fermarble/jobs/status_evening.py`. Nothing was uploaded.', '',
         '## Bundles', '',
         f"- upload candidate B (Pi3X heading on wide + flir-VIS, DPVO elsewhere): {bundle('submission_test_flow_pi3x.json')}; "
         'manifest label now `pi3x_heading`, predictions byte-identical',
         f"- fallback D (VGGT switch, mean of VGGT and Pi3X when it fires): {bundle('submission_test_flow_vggtpi3switch.json')}",
         f"- Pi3X 3-phase ensemble (only if it beats B on train and val): {bundle('submission_test_flow_pi3x3.json')}",
         f"- Pi3X speed (only if a speed variant beats flow on train and val): {bundle('submission_test_pi3x_speed.json')}", '']
    w = R / 'pi3x-speed/winner.txt'
    if w.is_file():
        L += [f"Speed winner (train-fitted variants that beat flow on train and val): {w.read_text().strip()}", '']
    note = R / 'pi3x-speed/NOTE.md'
    L += section('Pi3X speed vs flow v3a vs constant (B heading, dev)', R / 'pi3x-speed/compare.md', R / 'pi3_speed.log')
    if note.is_file():
        L.insert(len(L) - 1, '\n' + note.read_text().strip())
    L += section('Pi3X keyframe-phase ensemble (median of 3 runs) vs single-run B (dev)',
                 R / 'pi3x-ensemble/compare.md', R / 'pi3_ensemble.log')
    for split in ('dev', 'test'):
        for p in ('p1', 'p2'):
            s = R / f'pi3x-{split}-{p}/pi3x_summary.json'
            if s.is_file():
                j = json.loads(s.read_text())
                L.append(f"- Pi3X {split} {p}: {sum('error' not in v for v in j.values())} clips OK, "
                         f"{sum('error' in v for v in j.values())} errors")
    (R / 'status_evening.md').write_text('\n'.join(L) + '\n')
    print('written', R / 'status_evening.md')


if __name__ == '__main__':
    main()
